import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runSimulation } from '../src/game/simulation';
import { formatCurrency } from '../src/utils/format';

function argumentValue(name: string, fallback: number): number {
  const prefix = `--${name}=`;
  const argument = process.argv.find((value) => value.startsWith(prefix));
  if (!argument) return fallback;
  const parsed = Number(argument.slice(prefix.length));
  return Number.isFinite(parsed) ? parsed : fallback;
}

const spins = Math.max(1, Math.floor(argumentValue('spins', 1_000_000)));
const seed = Math.floor(argumentValue('seed', 2049));

console.log(`Running ${spins.toLocaleString()} deterministic spins with seed ${seed}…`);
const result = runSimulation(spins, seed);

const report = `# Neural Jackpot — Simulation Report

Generated by \`npm run simulate\`.

## Configuration

- Spins: ${result.spins.toLocaleString()}
- Seed: ${result.seed}
- Wager per spin: ${formatCurrency(result.wagerCents)}
- Theoretical RTP: ${(result.theoreticalRtp * 100).toFixed(6)}%
- Theoretical hit frequency per line: ${(
    result.theoreticalLineHitFrequency * 100
  ).toFixed(6)}%

## Results

- Empirical RTP: ${(result.empiricalRtp * 100).toFixed(6)}%
- Standard error: ${(result.standardError * 100).toFixed(6)} percentage points
- 95% confidence interval: ${(
    result.confidenceInterval95[0] * 100
  ).toFixed(6)}%–${(result.confidenceInterval95[1] * 100).toFixed(6)}%
- Hit frequency: ${(result.hitFrequency * 100).toFixed(6)}%
- Mean payout per spin: ${formatCurrency(result.meanPayoutCents)}
- Maximum observed payout: ${formatCurrency(result.maximumPayoutCents)}
- Maximum observed multiplier: ${result.maximumPayoutMultiplier.toFixed(4)}x the total wager

## Win distribution

| Band | Count | Frequency |
| --- | ---: | ---: |
| No win | ${result.winDistribution['no-win'].toLocaleString()} | ${(
    (result.winDistribution['no-win'] / result.spins) *
    100
  ).toFixed(6)}% |
| Under 1x | ${result.winDistribution['under-1x'].toLocaleString()} | ${(
    (result.winDistribution['under-1x'] / result.spins) *
    100
  ).toFixed(6)}% |
| 1x–5x | ${result.winDistribution['1x-5x'].toLocaleString()} | ${(
    (result.winDistribution['1x-5x'] / result.spins) *
    100
  ).toFixed(6)}% |
| 5x–20x | ${result.winDistribution['5x-20x'].toLocaleString()} | ${(
    (result.winDistribution['5x-20x'] / result.spins) *
    100
  ).toFixed(6)}% |
| 20x–100x | ${result.winDistribution['20x-100x'].toLocaleString()} | ${(
    (result.winDistribution['20x-100x'] / result.spins) *
    100
  ).toFixed(6)}% |
| 100x or more | ${result.winDistribution['100x-plus'].toLocaleString()} | ${(
    (result.winDistribution['100x-plus'] / result.spins) *
    100
  ).toFixed(6)}% |

## Symbol occurrences

${Object.entries(result.symbolCounts)
  .map(
    ([symbol, count]) =>
      `- ${symbol}: ${count.toLocaleString()} (${(
        (count / (result.spins * 15)) *
        100
      ).toFixed(6)}%)`,
  )
  .join('\n')}

The empirical result is a finite-sample estimate. The configured mathematical
RTP remains authoritative and is never changed in response to observed results.
`;

const reportPath = fileURLToPath(
  new URL('../docs/simulation-report.md', import.meta.url),
);
writeFileSync(reportPath, report, 'utf8');

console.log('--------------------------------------------');
console.log(`Theoretical RTP: ${(result.theoreticalRtp * 100).toFixed(6)}%`);
console.log(`Empirical RTP: ${(result.empiricalRtp * 100).toFixed(6)}%`);
console.log(
  `95% CI: ${(result.confidenceInterval95[0] * 100).toFixed(6)}%–${(
    result.confidenceInterval95[1] * 100
  ).toFixed(6)}%`,
);
console.log(`Hit frequency: ${(result.hitFrequency * 100).toFixed(6)}%`);
console.log(
  `Maximum observed payout: ${formatCurrency(
    result.maximumPayoutCents,
  )} (${result.maximumPayoutMultiplier.toFixed(4)}x wager)`,
);
console.log(`Report written to ${reportPath}`);
